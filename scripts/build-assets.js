// Bundles everything in public/ into src/assets.gen.js so the Worker can serve it
// directly. Run automatically by wrangler before `dev` and `deploy`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, extname, relative } from 'node:path';

const root = new URL('../public', import.meta.url).pathname;
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.svg': 'image/svg+xml' };
const out = {};
(function walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (TYPES[extname(p)]) {
      const body = readFileSync(p, 'utf8');
      out[`/${relative(root, p).replaceAll('\\', '/')}`] = { type: TYPES[extname(p)], etag: `"${createHash('sha256').update(body).digest('hex').slice(0, 16)}"`, body };
    }
  }
})(root);
writeFileSync(new URL('../src/assets.gen.js', import.meta.url), `// Generated by scripts/build-assets.js. Do not edit.\nexport const ASSETS = ${JSON.stringify(out)};\n`);
console.log(`Bundled ${Object.keys(out).length} static files`);
